"""tools/make_readme_policy: README blocks are generated from code (IAM policy, Billing cost sentence, import lines)."""
from __future__ import annotations

import pytest

from tools import make_readme_policy as mrp

FAKE = {"IAM POLICY": mrp.fenced_json('{"Version": "2012-10-17", "Statement": ["new"]}'),
        "BILLING NOTE": mrp.billing_note(7, "≈ $9.99 per account (test)"),
        "IMPORT POLICY": mrp.fenced_json('[{"Sid": "new"}]'),
        "COSTS": mrp.costs_section("≈ $9.99 per account (test)", "AWS charges $9 per check", "S3 bills (test)",
                                   "per token (test)")}
STALE = {name: "stale" for name in mrp.BLOCK_NAMES}


def _readme(tmp_path, blocks):
    path = tmp_path / "README.md"
    body = "\n\n".join(mrp.render_block(name, text) for name, text in blocks.items())
    path.write_text(f"# Title\n\nBefore.\n\n{body}\n\nAfter.\n", encoding="utf-8")
    return path


@pytest.fixture
def fake_blocks(monkeypatch):
    monkeypatch.setattr(mrp, "current_blocks", lambda: dict(FAKE))


def test_markers_and_iam_aliases():
    assert mrp.BEGIN == mrp.begin("IAM POLICY") and mrp.END == mrp.end("IAM POLICY")
    assert mrp.BLOCK_NAMES == ("IAM POLICY", "BILLING NOTE", "IMPORT POLICY", "COSTS")
    for name in mrp.BLOCK_NAMES:
        assert mrp.begin(name).startswith(f"<!-- BEGIN {name}: generated by") and mrp.end(name) == f"<!-- END {name} -->"


def test_render_block_and_fence():
    assert mrp.render_block("IAM POLICY", mrp.fenced_json("{}")) == f"{mrp.BEGIN}\n```json\n{{}}\n```\n{mrp.END}"


def test_billing_note_comes_from_its_inputs():
    text = mrp.billing_note(4, "≈ $0.04 per account (AWS Cost Explorer charges)")
    assert "about 4 requests per account: ≈ $0.04 per account (AWS Cost Explorer charges)." in text
    assert "$0.01 per request" in text and "never calls Cost Explorer" in text


def test_update_replaces_only_the_blocks():
    text = "intro\n" + "\n".join(mrp.render_block(n, "stale") for n in mrp.BLOCK_NAMES) + "\noutro\n"
    out = mrp.update_readme(text, FAKE)
    assert out == "intro\n" + "\n".join(mrp.render_block(n, FAKE[n]) for n in mrp.BLOCK_NAMES) + "\noutro\n"
    assert mrp.update_readme(out, FAKE) == out          # idempotent


@pytest.mark.parametrize("name", ["IAM POLICY", "BILLING NOTE", "IMPORT POLICY"])
@pytest.mark.parametrize("shape", ["missing", "begin only", "end only", "reversed", "twice"])
def test_update_rejects_bad_markers(name, shape):
    b, e = mrp.begin(name), mrp.end(name)
    text = {"missing": "none", "begin only": f"{b}\nx", "end only": f"x\n{e}", "reversed": f"{e}\n{b}",
            "twice": f"{b}{e}{b}{e}"}[shape]
    with pytest.raises(ValueError, match=name):
        mrp.update_block(text, name, "x")


def test_main_writes_then_check_passes(tmp_path, capsys, fake_blocks):
    path = _readme(tmp_path, STALE)
    assert mrp.main(["--check", "--readme", str(path)]) == 1
    assert "out of date" in capsys.readouterr().out
    assert mrp.main(["--readme", str(path)]) == 0
    text = path.read_text(encoding="utf-8")
    assert all(mrp.render_block(n, FAKE[n]) in text for n in mrp.BLOCK_NAMES)
    assert text.startswith("# Title\n\nBefore.\n") and text.endswith("\n\nAfter.\n")
    assert mrp.main(["--check", "--readme", str(path)]) == 0
    assert "current" in capsys.readouterr().out.splitlines()[-1]


def test_check_never_writes(tmp_path, fake_blocks):
    path = _readme(tmp_path, STALE)
    before = path.read_text(encoding="utf-8")
    mrp.main(["--check", "--readme", str(path)])
    assert path.read_text(encoding="utf-8") == before


def test_main_reports_a_missing_block(tmp_path, capsys, fake_blocks):
    path = _readme(tmp_path, {"IAM POLICY": "stale", "BILLING NOTE": "stale"})     # no IMPORT POLICY block
    assert mrp.main(["--readme", str(path)]) == 1
    assert "IMPORT POLICY" in capsys.readouterr().out


