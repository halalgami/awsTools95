def test_costs_section_lists_every_paid_action_from_the_constants():
    """Spec §2.1: the README's "What costs money" comes from the same constants the UI shows."""
    from aws95.contracts.billing import BILLING_CHECK_NOTE, BILLING_COST_NOTE, IMPORT_COST_NOTE
    from aws95.contracts.insights import INSIGHTS_COST_NOTE
    block = mrp.current_blocks()["COSTS"]
    for note in (BILLING_COST_NOTE, BILLING_CHECK_NOTE, IMPORT_COST_NOTE, INSIGHTS_COST_NOTE):
        assert note in block
    for action in ("Billing in snapshots", "Billing access check", "Import History", "AI Insights"):
        assert action in block
    assert "Everything else in the app is free to run" in block
