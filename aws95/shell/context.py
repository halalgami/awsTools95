"""What programs receive (ProgramContext) and what they may ask of the shell (ShellServices)."""
from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from datetime import datetime
from typing import TYPE_CHECKING, Any, Literal, Protocol

if TYPE_CHECKING:
    from PySide6.QtWidgets import QWidget

    from aws95.core.settings import Settings
    from aws95.core.tasks import TaskRunner
    from aws95.providers.base import ProviderSet


class SoundPlayer(Protocol):
    def play(self, event: str) -> bool: ...
    def preview(self, event: str) -> bool: ...


class NullSound:
    def play(self, event: str) -> bool:
        return False

    def preview(self, event: str) -> bool:
        return False


@dataclass(frozen=True)
class RecycledItem:
    program_id: str
    title: str
    closed_at: datetime


class RecycleBinModel(Protocol):
    changed: Any                       # Qt Signal()
    def items(self) -> tuple[RecycledItem, ...]: ...
    def restore(self, index: int) -> None: ...
    def empty(self) -> None: ...


class ShellServices(Protocol):
    sign_in_succeeded: Any             # Qt Signal(str): the CLI profile that just signed in
    snapshot_finished: Any             # Qt Signal(object): a snapshot ended (Result[SnapshotOutcome]); None after Clear Local Data
    snapshot_progress: Any             # Qt Signal(str): "dev: 7/42 sections · lambda me-south-1", "" when idle
    activity_finished: Any             # Qt Signal(object): an Activity job ended (Result[HistoryOutcome]); None after Clear Local Data
    activity_progress: Any             # Qt Signal(str): "Activity dev: 23/90 days · me-south-1", "" when idle
    def open_program(self, program_id: str) -> "QWidget | None": ...
    def navigate(self, program_id: str, params: Mapping[str, str]) -> None: ...
    def show_palette(self) -> None: ...
    def show_switcher(self) -> None: ...
    def show_start_menu(self) -> None: ...
    def request_shutdown(self) -> None: ...
    def preview_screensaver(self, name: str | None = None) -> None: ...
    def show_about(self) -> None: ...
    def open_setup_wizard(self, page: str | None = None) -> None: ...
    def check_permissions(self, profile: str, account_id: str) -> None: ...
    def sign_in(self, profile: str) -> None: ...
    def take_snapshot(self) -> None: ...
    def resume_snapshot(self, account_ids: Sequence[str] = (), retry_denied: bool = False) -> None: ...
    def cancel_snapshot(self) -> None: ...
    def clear_local_data(self) -> None: ...
    def load_activity(self, account_ids: Sequence[str] = ()) -> None: ...
    def update_activity(self, account_ids: Sequence[str] = ()) -> None: ...
    def resume_activity(self, account_ids: Sequence[str] = ()) -> None: ...
    def cancel_activity(self) -> None: ...
    def import_activity_history(self, account_id: str = "") -> None: ...
    def prune_activity(self) -> None: ...
    def tile(self, orientation: Literal["horizontal", "vertical"]) -> None: ...
    def cascade(self) -> None: ...
    def minimize_all(self) -> None: ...
    def recycle_bin(self) -> RecycleBinModel: ...


@dataclass
class ProgramContext:
    settings: "Settings"
    runner: "TaskRunner"
    providers: "ProviderSet"
    sound: SoundPlayer
    shell: ShellServices
