"""Generate README.md's code-derived blocks: the IAM policy, the Billing cost sentence and the Import History… lines.

`uv run python -m tools.make_readme_policy` rewrites every block between its markers;
`uv run python -m tools.make_readme_policy --check` writes nothing and exits 1 when README.md is out of date
(the test suite runs it). Never edit a generated block by hand: change the code it comes from, then regenerate.
"""
from __future__ import annotations

import argparse
from collections.abc import Mapping
from pathlib import Path

README = Path(__file__).resolve().parent.parent / "README.md"
BLOCK_NAMES: tuple[str, ...] = ("IAM POLICY", "BILLING NOTE", "IMPORT POLICY", "COSTS")

# The example trail that the Import History… lines are rendered for (placeholders only, spec §6.1).
EXAMPLE_BUCKET = "example-cloudtrail-bucket"
EXAMPLE_KMS_KEY = "arn:aws:kms:us-east-1:123456789012:key/EXAMPLE"


def begin(name: str) -> str:
    return f"<!-- BEGIN {name}: generated by `uv run python -m tools.make_readme_policy`; do not edit by hand -->"


def end(name: str) -> str:
    return f"<!-- END {name} -->"


BEGIN, END = begin("IAM POLICY"), end("IAM POLICY")


def fenced_json(text: str) -> str:
    return f"```json\n{text}\n```"


def billing_note(billed_calls: int, cost_note: str) -> str:
    """The README's cost sentence, built from 2b's BILLED_CALLS and BILLING_COST_NOTE (never typed by hand)."""
    return ("**Billing costs money.** Billing data comes from AWS Cost Explorer, which charges $0.01 per request. "
            f"A snapshot with Billing enabled makes about {billed_calls} requests per account: {cost_note}. "
            "Billing is off until you turn it on for an account, and the Billing window never calls Cost Explorer "
            "itself; it shows what the last snapshot collected.")


def costs_section(billing_note: str, check_note: str, import_note: str, insights_note: str) -> str:
    """Spec §2.1: the README's "What costs money" list, from the same constants the UI shows (never typed by hand)."""
    return "\n".join([
        "| Action | What AWS bills | About |",
        "|---|---|---|",
        f"| Billing in snapshots (opt-in per account) | AWS Cost Explorer requests | {billing_note} |",
        f"| The setup wizard's optional Billing access check | One AWS Cost Explorer request | {check_note} |",
        f"| Import History… (Activity) | S3 requests and data transfer | {import_note} |",
        f"| AI Insights (on Analyze) | Amazon Bedrock model calls | {insights_note} |",
        "",
        "Everything else in the app is free to run: opening windows, snapshots without Billing, the CloudTrail "
        "lookups behind Activity, and the identity and permission checks make no billed requests.",
    ])


def render_block(name: str, body: str) -> str:
    return f"{begin(name)}\n{body}\n{end(name)}"


def update_block(text: str, name: str, body: str) -> str:
    """`text` with block `name` replaced. ValueError unless exactly one BEGIN followed by one END."""
    b, e = begin(name), end(name)
    if text.count(b) != 1 or text.count(e) != 1 or text.index(b) > text.index(e):
        raise ValueError(f"README.md needs exactly one BEGIN {name} marker followed by one END {name} marker")
    start, stop = text.index(b), text.index(e) + len(e)
    return text[:start] + render_block(name, body) + text[stop:]


def update_readme(text: str, blocks: Mapping[str, str]) -> str:
    for name, body in blocks.items():
        text = update_block(text, name, body)
    return text


def current_blocks() -> dict[str, str]:
    """Every generated block, from the app's own code. Imported lazily: tools/ stays outside the layer rules."""
    from aws95.aws.engines.labsnap.collect.collectors.cost import BILLED_CALLS
    from aws95.aws.permissions import import_policy, policy_json
    from aws95.contracts.billing import BILLING_CHECK_NOTE, BILLING_COST_NOTE, IMPORT_COST_NOTE
    from aws95.contracts.insights import INSIGHTS_COST_NOTE

    return {
        "IAM POLICY": fenced_json(policy_json()),
        "BILLING NOTE": billing_note(BILLED_CALLS, BILLING_COST_NOTE),
        "IMPORT POLICY": fenced_json(import_policy(EXAMPLE_BUCKET, "", EXAMPLE_KMS_KEY)),
        "COSTS": costs_section(BILLING_COST_NOTE, BILLING_CHECK_NOTE, IMPORT_COST_NOTE, INSIGHTS_COST_NOTE),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="make_readme_policy", description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if README.md is out of date; write nothing")
    parser.add_argument("--readme", type=Path, default=README)
    args = parser.parse_args(argv)

    current = args.readme.read_text(encoding="utf-8")
    try:
        updated = update_readme(current, current_blocks())
    except ValueError as exc:
        print(f"{args.readme.name}: {exc}")
        return 1
    if args.check:
        if updated != current:
            print(f"{args.readme.name}: generated blocks are out of date. Run: uv run python -m tools.make_readme_policy")
            return 1
        print(f"{args.readme.name}: generated blocks are current")
        return 0
    if updated != current:
        args.readme.write_text(updated, encoding="utf-8")
        print(f"{args.readme.name}: generated blocks updated")
    else:
        print(f"{args.readme.name}: generated blocks already current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
